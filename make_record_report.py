def glow(line, lw: float = 8.0, alpha: float = 0.28) -> None:
    """Lay a soft, wide stroke of the line's own color behind it — neon under-glow."""
    line.set_path_effects([pe.Stroke(linewidth=lw, foreground=line.get_color(), alpha=alpha),
                           pe.Normal()])


def first_cross(x, y, target: float) -> float | None:
    """First x-value at which series y reaches `target` (None if it never does)."""
    xa, ya = np.asarray(x, float), np.asarray(y, float)
    hit = np.flatnonzero(ya >= target)
    return float(xa[hit[0]]) if hit.size else None


def fmt_clock(seconds: float) -> str:
    """mm:ss — runs are assumed under an hour for now."""
    s = int(seconds)
    return f"{s // 60}:{s % 60:02d}"


def pct_axis(ax) -> None:
    ax.yaxis.set_major_formatter(PercentFormatter(xmax=1.0, decimals=0))


def smooth(s):
    """Rolling-mean trend line; min_periods=1 so the early steps still render."""
    return s.rolling(SMOOTH, min_periods=1).mean()


def normalize_wandb_run(run_path: str) -> str:
    """Accept either entity/project/run_id or a wandb.ai run URL."""
    run_path = run_path.strip()
    if not run_path.startswith(("http://", "https://")):
        return run_path.strip("/")
    parsed = urlparse(run_path)
    parts = [p for p in parsed.path.split("/") if p]
    if len(parts) >= 4 and parts[2] == "runs":
        return f"{parts[0]}/{parts[1]}/{parts[3]}"
    raise SystemExit(f"could not parse W&B run URL: {run_path}")


def online_metric_col(df: pd.DataFrame) -> str:
    for col in ONLINE_METRIC_ALIASES:
        if col in df.columns:
            return col
    raise SystemExit(
        f"online metric history needs one of {', '.join(ONLINE_METRIC_ALIASES)}"
    )


def normalize_online_frame(df: pd.DataFrame) -> pd.DataFrame:
    if "step" not in df.columns:
        raise SystemExit("online metric history needs a step column")
    col = online_metric_col(df)
    out = df[["step", col]].dropna().rename(columns={col: ONLINE_METRIC}).copy()
    out["step"] = out["step"].astype(int)
    out[ONLINE_METRIC] = out[ONLINE_METRIC].astype(float)
    return out.sort_values("step").drop_duplicates("step", keep="last").reset_index(drop=True)


def aligned_training_series(log: dict, online_frame: pd.DataFrame | None = None) -> dict:
    """Return x/y vectors for the training plot and a precise metric label."""
    df = log["df"]
    if online_frame is None:
        return {
            "raw": df.solved_frac.reset_index(drop=True),
            "xstep": df.step.reset_index(drop=True),
            "xclock": (df.record_time_s / 60.0).reset_index(drop=True),
            "label": FILTERED_TRAIN_LABEL,
            "source": "filtered",
        }

    w = normalize_online_frame(online_frame)
    log_by_step = df.set_index("step")["record_time_s"]
    step_values = w["step"].astype(int)
    if step_values.add(1).isin(log_by_step.index).all():
        # W&B logs the loop's zero-based step; RunLogger prints one-based step:N/total.
        plot_step = step_values + 1
    elif step_values.isin(log_by_step.index).all():
        plot_step = step_values
    else:
        n = min(len(w), len(df))
        w = w.iloc[:n].reset_index(drop=True)
        return {
            "raw": w[ONLINE_METRIC],
            "xstep": df.step.iloc[:n].reset_index(drop=True),
            "xclock": (df.record_time_s.iloc[:n] / 60.0).reset_index(drop=True),
            "label": ONLINE_TRAIN_LABEL,
            "source": "online",
        }

    return {
        "raw": w[ONLINE_METRIC].reset_index(drop=True),
        "xstep": plot_step.reset_index(drop=True),
        "xclock": (plot_step.map(log_by_step) / 60.0).reset_index(drop=True),
        "label": ONLINE_TRAIN_LABEL,
        "source": "online",
    }


def target_line(ax, value: float, label: str, color: str = TARGET_C) -> None:
    """Dashed horizontal reference + a left-anchored label (blended transform so
    the label hugs the left spine regardless of the x-scale)."""
    ax.axhline(value, color=color, ls=DASH, lw=1.6, alpha=0.9)
    ax.annotate(label, xy=(0.012, value), xycoords=ax.get_yaxis_transform(),
                xytext=(0, 5), textcoords="offset points",
                color=color, fontsize=11, fontweight="bold")


def draw_speedrun(ax, df, color: str, target: float, annotate: bool = True) -> float | None:
    """The signature panel: smoothed solve-rate vs record clock with a raw ghost
    underneath, gradient fill, neon glow, and the target-crossing marker.
    Returns the wall-clock minute the smoothed curve first hits `target`."""
    x = df.record_time_s / 60.0
    sm = smooth(df.solved_frac)
    ax.plot(x, df.solved_frac, color=color, alpha=0.10, lw=1.0)
    glow(ax.plot(x, sm, color=color, alpha=0.97)[0], lw=9, alpha=0.32)
    ax.fill_between(x, sm, color=color, alpha=0.12)
    xc = first_cross(x, sm, target)
    if xc is not None:
        ax.scatter([xc], [target], s=90, color=color, zorder=7, edgecolor=BG, linewidth=2)
        if annotate:
            ax.annotate(f"target reached\n@ {xc:.0f} min", xy=(xc, target),
                        xytext=(-12, 16), textcoords="offset points", ha="right", va="bottom",
                        color=INK, fontsize=13, fontweight="bold")
    return xc


def fmt_flops(f: float | None) -> str:
    """Raw FLOPs-to-target (the node-invariant leaderboard metric).

    Reported as the exact FLOP count in scientific notation (matching the ``.6e``
    cum_flops format in the train logs) rather than rounded to ``EFLOP``: this is a
    speedrun metric where small gaps decide records, so no unit-rounding."""
    if f is None or not (isinstance(f, (int, float)) and math.isfinite(f)) or f <= 0:
        return "—"
    return f"{f:.6e}"


def train_log_paths(record_dir: Path) -> list[Path]:
    return [
        p for p in sorted(record_dir.glob("train_log_seed*.txt"))
        if not p.name.endswith(".flops.txt")
    ]


def extract_speedrun_source_from_log(path: Path) -> str:
    text = path.read_text(encoding="utf-8", errors="replace")
    source, sep, _rest = text.partition(f"\n{SOURCE_DIVIDER}\n")
    if not sep:
        raise ValueError(f"{path}: could not find run-log source divider")
    if source.startswith("<source unavailable:"):
        raise ValueError(f"{path}: embedded speedrun.py source is unavailable")
    return source if source.endswith("\n") else source + "\n"


def source_snapshot_path(record_dir: Path, seed: str) -> Path:
    return record_dir / "source" / f"speedrun_{seed}.py"


def ensure_source_snapshots(record_dir: Path) -> list[dict]:
    """Ensure source/speedrun_<seed>.py exists and matches the source embedded in each log."""
    rows = []
    for log_path in train_log_paths(record_dir):
        seed = log_path.stem.replace("train_log_", "")
        dest = source_snapshot_path(record_dir, seed)
        embedded = extract_speedrun_source_from_log(log_path)
        if not dest.exists():
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(embedded, encoding="utf-8")
        snapshot = dest.read_text(encoding="utf-8")
        if snapshot != embedded:
            raise SystemExit(f"{dest}: does not match source embedded in {log_path}")
        sha = hashlib.sha256(snapshot.encode("utf-8")).hexdigest()
        rows.append({"seed": seed, "path": dest, "sha256": sha})
    return rows


def ensure_all_source_snapshots(record_dir: Path) -> list[dict]:
    rows = [{"run": "submission", **row} for row in ensure_source_snapshots(record_dir)]
    verification_dir = record_dir / "verification"
    if verification_dir.is_dir():
        rows.extend({"run": "verification", **row} for row in ensure_source_snapshots(verification_dir))
    return rows


def parse_train_log(path: Path) -> dict:
    """Extract the per-step record-clock series and the args attestation from a run log."""
    steps, args_dict = [], None
    for line in path.read_text(errors="replace").splitlines():
        m = STEP_RE.match(line)
        if m:
            steps.append({
                "step": int(m.group(1)), "record_time_s": float(m.group(3)),
                "reward_mean": float(m.group(4)), "solved_frac": float(m.group(5)),
                "loss": float(m.group(6)), "grad_norm": float(m.group(7)),
                "cum_flops": float(m.group(8)) if m.group(8) else float("nan"),
            })
        elif line.startswith("args: {") and args_dict is None:
            # The attestation prints repr(vars(args)); PosixPath is its only non-literal.
            args_dict = eval(  # noqa: S307 — sandboxed: no builtins, PosixPath -> str
                line[len("args: "):], {"__builtins__": {}}, {"PosixPath": lambda p: p})
        elif line.startswith("final_checkpoint:"):
            m2 = re.search(r"record_time:([\d.]+)s", line)
            if m2 and steps:
                steps[-1]["final_record_time_s"] = float(m2.group(1))
            mf = re.search(r"cum_flops:([\d.eE+-]+)", line)
            if mf and steps:
                steps[-1]["cum_flops"] = float(mf.group(1))
    if not steps:
        raise ValueError(f"{path}: no step lines found")
    df = pd.DataFrame(steps)
    final_time = steps[-1].get("final_record_time_s", df.record_time_s.iloc[-1])
    final_flops = steps[-1].get("cum_flops", df.cum_flops.iloc[-1])
    # Records whose log predates cum_flops can carry a `<log_stem>.flops.txt` sidecar with the
    # FLOPs-to-target reconstructed from W&B (per-step perf_est/total_flops summed to target).
    if not (isinstance(final_flops, float) and math.isfinite(final_flops)):
        sidecar = path.with_suffix(".flops.txt")
        if sidecar.exists():
            final_flops = float(sidecar.read_text().split()[0])
    return {"df": df, "args": args_dict or {}, "final_time_s": final_time,
            "final_flops": final_flops}


def load_record(record_dir: Path) -> dict:
    logs, evals = {}, {}
    for p in train_log_paths(record_dir):
        logs[p.stem.replace("train_log_", "")] = parse_train_log(p)
    for p in sorted(record_dir.glob("eval_seed*.json")):
        evals[p.stem.replace("eval_", "").split(".")[0]] = json.loads(p.read_text())
    if not logs or not evals:
        raise SystemExit(f"{record_dir}: need train_log_seed*.txt and eval_seed*.json")
    return {"logs": logs, "evals": evals, "name": record_dir.name}


def load_metrics_frames(record_dir: Path, seeds: list[str]) -> list[pd.DataFrame] | None:
    """Per-seed metrics_seed<seed>.jsonl written by speedrun.py's RunLogger — the offline
    stand-in for fetch_wandb_history (record runs are --no-wandb). All-or-nothing: every
    seed log must have its metrics file, else fall back to the filtered step: lines."""
    paths = [record_dir / f"metrics_{seed}.jsonl" for seed in seeds]
    if not paths or not all(p.exists() for p in paths):
        return None
    return [normalize_online_frame(pd.read_json(p, lines=True)) for p in paths]


def fetch_wandb_history(run_paths: list[str]) -> list[pd.DataFrame]:
    """One normalized DataFrame per run with step + train solve rate."""
    import wandb
    api = wandb.Api()
    frames = []
    for rp in run_paths:
        rp = normalize_wandb_run(rp)
        # Full history rather than scan_history(keys=...): keyed scans drop rows missing
        # any requested key, which silently empties the result for sparse metrics.
        df = api.run(rp).history(samples=100_000, pandas=True)
        frames.append(normalize_online_frame(df))
    return frames


def plot_training(record: dict, online_frames: list[pd.DataFrame] | None, out: Path,
                  target: float = 0.80) -> None:
    """Solve rate vs record-clock minutes.

    Prefer the train metric from W&B/history artifacts. The leaderboard
    target is intentionally omitted here: the target gate is held-out eval CI, not a
    train-curve threshold.
    """
    fig, ax = plt.subplots(figsize=(9.2, 5.0))
    multi = len(record["logs"]) > 1
    src, ymax = ONLINE_TRAIN_LABEL if online_frames is not None else FILTERED_TRAIN_LABEL, 0.0
    for i, (seed, log) in enumerate(record["logs"].items()):
        c = SEED_COLORS[i % len(SEED_COLORS)]
        series = aligned_training_series(log, online_frames[i] if online_frames is not None else None)
        raw, xclock = series["raw"], series["xclock"]
        sm = smooth(raw)
        ymax = max(ymax, float(sm.max()))
        ax.plot(xclock, raw, color=c, alpha=0.10, lw=1.0)
        glow(ax.plot(xclock, sm, color=c, alpha=0.96, label=seed)[0], lw=8, alpha=0.28)
        ax.fill_between(xclock, sm, color=c, alpha=0.11)
    ax.set_ylim(0, max(ymax, target) * 1.12); pct_axis(ax)
    ax.set_xlabel("record clock (minutes)")
    ax.set_ylabel(src)
    ax.set_title(f"Train solve rate vs record clock  ·  {SMOOTH}-step rolling mean")
    if multi:
        ax.legend(loc="lower right")
    fig.savefig(out); plt.close(fig)


def plot_stability(record: dict, out: Path) -> None:
    """Grad norm (pre-clip, log) with the clip threshold drawn in; loss with a
    bold rolling mean over its raw ghost."""
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.4))
    multi, clip = len(record["logs"]) > 1, None
    for i, (seed, log) in enumerate(record["logs"].items()):
        df, c = log["df"], SEED_COLORS[i % len(SEED_COLORS)]
        glow(axes[0].plot(df.step, df.grad_norm, color=c, alpha=0.9, label=seed)[0], lw=6, alpha=0.16)
        axes[1].plot(df.step, df.loss, color=c, alpha=0.20, lw=1.2)
        glow(axes[1].plot(df.step, smooth(df.loss),
                          color=c, alpha=0.96, label=seed)[0], lw=6, alpha=0.16)
        clip = clip if clip is not None else log["args"].get("grad_clip")
    if clip is not None:
        target_line(axes[0], float(clip), f"clip {float(clip):g}")
    axes[0].set_yscale("log"); axes[0].set_title("Gradient norm  ·  pre-clip")
    axes[1].set_title("Loss")
    for ax in axes:
        ax.set_xlabel("training step")
        if multi:
            ax.legend(loc="best")
    fig.savefig(out); plt.close(fig)


def plot_eval(record: dict, target: float, out: Path) -> None:
    """pass@k curve with the bootstrap CI on pass@1 and the capability band above
    target — the capability-expansion view."""
    evals = record["evals"]
    multi = len(evals) > 1
    fig, ax = plt.subplots(figsize=(9, 5.2))
    ks = [1]
    for i, (seed, ev) in enumerate(evals.items()):
        c = SEED_COLORS[i % len(SEED_COLORS)]
        ks = sorted(int(k) for k in ev["pass_at_k"])
        ys = [ev["pass_at_k"][str(k)] for k in ks]
        ax.fill_between(ks, ys, target, color=c, alpha=0.07)
        glow(ax.plot(ks, ys, "o-", color=c, ms=9, label=seed, zorder=5)[0], lw=7, alpha=0.22)
        lo, hi = ev.get("ci_low"), ev.get("ci_high")
        if lo is not None and hi is not None:
            ax.errorbar([1], [ev["pass_at_1"]], yerr=[[ev["pass_at_1"] - lo], [hi - ev["pass_at_1"]]],
                        color=c, capsize=5, lw=2.2, zorder=6)
        for k, y in zip(ks, ys):
            ax.annotate(f"{y:.0%}", (k, y), xytext=(0, 11), textcoords="offset points",
                        ha="center", color=INK, fontsize=11, fontweight="bold")
    target_line(ax, target, f"TARGET {target:g}")
    ax.set_xscale("log", base=2); ax.set_xticks(ks, [str(k) for k in ks])
    ax.set_xlabel("k (samples per puzzle)"); ax.set_ylabel("pass@k")
    pct_axis(ax); ax.set_ylim(max(0.0, target - 0.1), 1.06)
    ax.set_title("Capability  ·  pass@k vs target")
    if multi:
        ax.legend(loc="lower right")
    fig.savefig(out); plt.close(fig)


def plot_hero_card(record: dict, target: float, out: Path,
                   online_frames: list[pd.DataFrame] | None = None, subtitle: str = "") -> None:
    """Clean 16:9 record card: training climb, record time, pass@1, target."""
    logs, evals = record["logs"], record["evals"]
    fig = plt.figure(figsize=(12.8, 7.2), constrained_layout=False)
    gs = fig.add_gridspec(1, 2, width_ratios=[1.5, 1.0],
                          left=0.065, right=0.965, top=0.80, bottom=0.13, wspace=0.11)
    ax_main = fig.add_subplot(gs[0, 0])
    ax_card = fig.add_subplot(gs[0, 1]); ax_card.axis("off")

    fig.text(0.065, 0.93, "Sokoban Speedrun", fontsize=36, fontweight="bold",
             color=INK, ha="left", va="center")
    if subtitle:
        fig.text(0.066, 0.872, subtitle, fontsize=15, fontweight="bold",
                 color=MUTED, ha="left", va="center")

    smax = 0.0
    source = "filtered"
    for i, log in enumerate(logs.values()):
        series = aligned_training_series(log, online_frames[i] if online_frames is not None else None)
        x, raw_y = series["xclock"], series["raw"]
        y = smooth(raw_y)
        smax = max(smax, float(y.max()))
        source = series["source"]
        color = SEED_COLORS[i % len(SEED_COLORS)]
        ax_main.plot(x, raw_y, color=color, alpha=0.10, lw=1.0)
        glow(ax_main.plot(x, y, color=color, alpha=0.97)[0], lw=9, alpha=0.28)
        ax_main.fill_between(x, y, color=color, alpha=0.12)
        ax_main.scatter([x.iloc[-1]], [y.iloc[-1]], s=72, color=color, zorder=7,
                        edgecolor=BG, linewidth=1.8)
    ax_main.set_ylim(0.32, max(0.78, smax * 1.08)); pct_axis(ax_main)
    ax_main.set_xlabel("minutes")
    ax_main.set_ylabel(ONLINE_TRAIN_LABEL if source == "online" else FILTERED_TRAIN_LABEL)
    ax_main.set_title("")

    final_time = logs[sorted(logs)[0]]["final_time_s"]
    p1s = [e["pass_at_1"] for e in evals.values()]
    p1 = sum(p1s) / len(p1s)

    ax_card.text(0.0, 0.82, "RECORD", color=MUTED, fontsize=17,
                 fontweight="bold", va="top")
