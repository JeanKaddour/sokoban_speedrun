def verification_block(record_dir: Path, target: float) -> list[str]:
    """Render the ## Verification section from a nested verification/ mini-record, if present.

    verification/ is itself a record dir — an independent rerun (train_log_seed*.txt +
    eval_seed*.json + rollouts) plus an optional one-line verifier.txt (e.g. '@maintainer  PR#12'
    or 'Self-verified by the maintainers'). The verdict is derived from the eval JSON, so it can
    never drift from the committed artifacts; the track verifier re-scores it too."""
    vdir = record_dir / "verification"
    vevals = sorted(vdir.glob("eval_seed*.json")) if vdir.is_dir() else []
    if not vevals:
        return []
    att = vdir / "verifier.txt"
    who = (att.read_text().strip().splitlines()[0].strip()
           if att.exists() and att.read_text().strip() else "Verifier unrecorded")
    lines = ["## Verification", "", f"{who}:", ""]
    for p in vevals:
        ev = json.loads(p.read_text())
        seed = p.stem.replace("eval_", "").split(".")[0]
        clears = ev["ci_low"] > target
        commit = ev.get("git_commit")
        commit_txt = f", recipe commit `{commit[:10]}`" if commit else ""
        lines.append(
            f"- re-ran at {seed}{commit_txt} → pass@1 **{ev['pass_at_1']:.4f}** "
            f"(95% CI [{ev['ci_low']:.4f}, {ev['ci_high']:.4f}]) — "
            f"**{'CLEARS' if clears else 'DOES NOT CLEAR'} {target}** {'✓' if clears else '✗'}")
    lines += ["", "Confirms the recipe reproduces independently; the record time above is the "
              "submission run's, not this rerun's. Artifacts: [`verification/`](verification/).", ""]
    return lines


