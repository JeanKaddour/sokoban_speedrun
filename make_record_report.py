def _track_path_prefix(track: str) -> str:
    """Repo-relative dir for a track ('llm' / 'non_llm') — note the TRACKS key is 'non-llm'."""
    return "non_llm" if track == "non-llm" else "llm"


def update_leaderboard_row(record_dir: Path, track: str) -> None:
    """Insert (or refresh) this record's row in the README world-record table, then redraw the
    figures. The derived columns (record time, date, log link, pass@1/CI) are read from the
    record's own artifacts; Description and Contributors are human-authored, so a new row gets
    placeholders to fill in and an existing row keeps whatever is already there."""
    rec = load_record(record_dir)
    seed = sorted(rec["logs"])[0]
    s = int(rec["logs"][seed]["final_time_s"])
    clock = fmt_clock(s)  # mm:ss (both tracks' headers)
    # Report the WORST of the required seeds (submission run + verification rerun), not the
    # submission seed alone. Both seeds must clear the bar, so the binding (lower) one is the
    # honest, un-cherry-pickable quality signal — it stops a submitter from seed-shopping the
    # headline. The *ranking* is still wall-clock (the submission run's clock, set above).
    eval_paths = sorted(record_dir.glob("eval_seed*.json")) + \
        sorted((record_dir / "verification").glob("eval_seed*.json"))
    ev = min((json.loads(p.read_text()) for p in eval_paths), key=lambda e: e["pass_at_1"])
    acc = f"{ev['pass_at_1']:.3f} (CI [{ev['ci_low']:.2f}, {ev['ci_high']:.2f}])"

    name = record_dir.name                                     # e.g. 2026-06-29_01_grpo
    m = re.match(r"(\d{4}-\d{2}-\d{2})_(\d+)", name)
    date = m.group(1) if m else "<date>"
    label = f"{m.group(1)}_{m.group(2)}" if m else name        # 2026-06-29_01 (drops the name suffix)
    prefix = _track_path_prefix(track)
    link = f"[{prefix}/records/{label}]({prefix}/records/{name}/)"

    section = TRACKS[track]["lb_section"]                       # "LLM Track" / "Non-LLM Track"
    readme = REPO_ROOT / "README.md"
    lines = readme.read_text().splitlines()

    # The section's data rows run from its `## <section>` heading to the next `## ` heading.
    start = next((i for i, ln in enumerate(lines) if ln.strip() == f"## {section}"), None)
    if start is None:
        raise SystemExit(f"README.md has no '## {section}' section to update")
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    data_rows = [i for i in range(start, end) if re.match(r"\|\s*\d+\s*\|", lines[i])]
    cells = lambda i: [c.strip() for c in lines[i].strip().strip("|").split("|")]

    existing = next((i for i in data_rows if name in cells(i)[4]), None)
    if existing is not None:
        c = cells(existing)
        new = [c[0], clock, c[2], date, link, acc, c[6]]       # keep human-authored Description + Contributors
        if new == c:
            print(f"leaderboard: row #{c[0]} for {name} already current")
        else:
            lines[existing] = "| " + " | ".join(new) + " |"
            print(f"leaderboard: refreshed row #{c[0]} for {name}")
    else:
        num = max((int(cells(i)[0]) for i in data_rows), default=0) + 1
        desc, contrib = "<describe: algorithm, key hparams, steps>", "@you"
        row = f"| {num} | {clock} | {desc} | {date} | {link} | {acc} | {contrib} |"
        after = data_rows[-1] if data_rows else next(
            i for i in range(start, end) if re.match(r"\|\s*-+\s*\|", lines[i]))
        lines.insert(after + 1, row)
        print(f"leaderboard: added row #{num} for {name} — fill in Description + Contributors in README.md")

    readme.write_text("\n".join(lines) + "\n")
    make_leaderboard()


def source_block(record_dir: Path, source_rows: list[dict], script: str = "speedrun.py") -> list[str]:
    if not source_rows:
        return []
    lines = [
        "## Source",
        "",
        f"Standalone `{script}` snapshots are saved per run and checked against the embedded run-log source.",
        "",
        "| run | seed | snapshot | sha256 |",
        "|---|---|---|---|",
    ]
    for row in source_rows:
        rel = row["path"].relative_to(record_dir).as_posix()
        lines.append(
            f"| {row['run']} | {row['seed']} | [{rel}]({rel}) | `{row['sha256'][:12]}` |"
        )
    lines.append("")
    return lines


def auto_block(record: dict, record_dir: Path, target: float, prev_dir: Path | None,
               source_rows: list[dict], track: str = "llm") -> str:
    evals, logs = record["evals"], record["logs"]
    clocks = {s: logs[s]["final_time_s"] for s in sorted(logs)}
    flops = {s: logs[s].get("final_flops") for s in sorted(logs)}
    show_flops = TRACKS[track].get("show_flops", True)   # non-LLM track has no FLOPs co-metric
    flops_hdr, flops_sep = (" FLOPs |", "---|") if show_flops else ("", "")
    lines = ["## Results", "", f"| seed | held-out eval pass@1 | 95% CI | record clock |{flops_hdr}",
             f"|---|---|---|---|{flops_sep}"]
    for s in sorted(evals):
        ev, clock, fl = evals[s], clocks.get(s), flops.get(s)
        hms = fmt_clock(clock) if clock else "—"
        flo = f" {fmt_flops(fl)} |" if show_flops else ""
        lines.append(f"| {s} | {ev['pass_at_1']:.4f} | [{ev['ci_low']:.4f}, {ev['ci_high']:.4f}] "
                     f"| {hms} |{flo}")
    # Single-seed gate: each run independently clears the target via its lower 95% bootstrap CI
    # (no cross-seed averaging — see the leaderboard rules).
    if len(evals) == 1:
        only = evals[sorted(evals)[0]]
        verdict = "CLEARS" if only["ci_low"] > target else "DOES NOT CLEAR"
        summary = (f"**Held-out eval pass@1 {only['pass_at_1']:.4f}, lower 95% CI "
                   f"{only['ci_low']:.4f} vs TARGET {target}: {verdict}.**")
    else:
        all_clear = all(ev["ci_low"] > target for ev in evals.values())
        summary = (f"**Each of {len(evals)} runs vs TARGET {target} by its lower 95% CI: "
                   f"{'ALL CLEAR' if all_clear else 'NOT ALL CLEAR'}.**")
    lines += ["", summary, "",
              "![hero](plots/hero.png)", "",
              "![training](plots/training.png)", "",
              "<details><summary>diagnostic plots</summary>", "",
              "![stability](plots/stability.png)", "",
              "![eval](plots/eval.png)", "",
              "</details>", ""]
    lines += verification_block(record_dir, target)
    lines += source_block(record_dir, source_rows, TRACKS[track]["script"])
    # Config: headline table + diff vs previous record + full dict.
    args = logs[sorted(logs)[0]]["args"]
    lines += ["## Config", "", "| arg | value |", "|---|---|"]
    lines += [f"| `{k}` | `{args[k]}` |" for k in HEADLINE_ARGS if k in args]
    if prev_dir is not None:
        prev_logs = train_log_paths(prev_dir)
        if prev_logs:
            prev_args = parse_train_log(prev_logs[0])["args"]
            diffs = [(k, prev_args.get(k, "—"), args[k]) for k in sorted(args)
                     if k != "run" and str(args[k]) != str(prev_args.get(k))]
            if diffs:
                lines += ["", f"**Changed vs [{prev_dir.name}](../{prev_dir.name}/):**", "",
                          "| arg | before | after |", "|---|---|---|"]
                lines += [f"| `{k}` | `{b}` | `{a}` |" for k, b, a in diffs]
    full = json.dumps({k: str(v) for k, v in sorted(args.items())}, indent=2)
    lines += ["", "<details><summary>full args</summary>", "", "```json", full, "```", "</details>", ""]
    verify_cmds = [cmd.format(record=record_dir.as_posix()) for cmd in TRACKS[track]["verify"]]
    lines += ["## Reproduce", "", "```bash", *TRACKS[track]["reproduce"], *verify_cmds, "```", ""]
    return "\n".join(lines)


def write_readme(record_dir: Path, block: str) -> None:
    readme = record_dir / "README.md"
    auto = f"{AUTO_BEGIN}\n\n{block}\n{AUTO_END}\n"
    if readme.exists():
        text = readme.read_text()
        if AUTO_BEGIN in text and AUTO_END in text:
            pre, rest = text.split(AUTO_BEGIN, 1)
            _, post = rest.split(AUTO_END, 1)
            readme.write_text(pre + auto + post)
            return
        readme.write_text(text.rstrip() + "\n\n" + auto)
        return
    title = record_dir.name
    readme.write_text(
        f"# {title}\n\n## Idea\n\nTODO: describe the recipe — what changed vs the previous "
        f"record, why it should be faster, and anything a reader should know before "
        f"trusting/forking it.\n\n{auto}")


def infer_track(record_dir: Path) -> str:
    """Infer the speedrun track from the normal `cd llm` / `cd non_llm` workflow."""
    paths = [record_dir.resolve(), Path.cwd().resolve()]
    for path in paths:
        parts = set(path.parts)
        if "non_llm" in parts:
            return "non-llm"
        if "llm" in parts:
            return "llm"
    return "llm"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("record_dir", type=Path, nargs="?",
                    help="record dir to report on (omit with --leaderboard)")
    ap.add_argument("--leaderboard", action="store_true",
                    help="regenerate the README world-record figures (assets/*.png) from the leaderboard tables, then exit")
    ap.add_argument("--update-leaderboard", action="store_true",
                    help="after writing the per-record report, insert/refresh this record's row in the "
                         "README world-record table and redraw the figures (Description/Contributors left for you)")
    ap.add_argument("--wandb-runs", default=None,
                    help="comma-separated entity/project/run_id list, one per seed, ordered like the seed files")
    ap.add_argument("--prev", type=Path, default=None, help="previous record dir for the config diff")
    ap.add_argument("--target", type=float, default=None,
                    help="override the selected track's target threshold")
    ap.add_argument("--subtitle", default="", help="optional hero subtitle, e.g. a track label")
    ap.add_argument("--track", choices=["llm", "non-llm"], default=None,
                    help="override the inferred record track")
    args = ap.parse_args()

    if args.leaderboard:
        make_leaderboard()
        return
    if args.record_dir is None:
        ap.error("record_dir is required (or pass --leaderboard)")

    track = args.track or infer_track(args.record_dir)
    target = args.target if args.target is not None else TRACKS[track]["target"]

    set_house_style()
    record = load_record(args.record_dir)
    plots = args.record_dir / "plots"
    plots.mkdir(exist_ok=True)

    seeds = sorted(record["logs"])
    online_frames = None
    if args.wandb_runs:
        online_frames = fetch_wandb_history([r.strip() for r in args.wandb_runs.split(",")])
        if len(online_frames) != len(seeds):
            raise SystemExit(f"got {len(online_frames)} W&B runs for {len(seeds)} seed logs")
    else:
        online_frames = load_metrics_frames(args.record_dir, seeds)
        if online_frames is not None:
            print(f"using metrics_seed*.jsonl for the online train metric ({len(seeds)} seed(s))")

    plot_training(record, online_frames, plots / "training.png", target)
    plot_stability(record, plots / "stability.png")
    plot_eval(record, target, plots / "eval.png")
    plot_hero_card(record, target, plots / "hero.png", online_frames, subtitle=args.subtitle)

    source_rows = ensure_all_source_snapshots(args.record_dir)
    write_readme(args.record_dir,
                 auto_block(record, args.record_dir, target, args.prev, source_rows, track=track))
    print(f"wrote {plots}/*.png (incl. hero.png) and updated {args.record_dir / 'README.md'}")

    if args.update_leaderboard:
        update_leaderboard_row(args.record_dir, track)


if __name__ == "__main__":
    main()
